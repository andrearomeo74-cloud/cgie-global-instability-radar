def write_scientific_outputs(
    context: ExperimentContext,
    summary: Mapping[str, Any],
    report_text: str,
    manifest: Mapping[str, Any],
) -> dict[str, str]:
    """Write all required scientific outputs and return their hashes."""
    candidate_relations = require_dataframe(
        context.outputs[
            "candidate_relations"
        ],
        "candidate_relations",
    )

    block_relations = require_dataframe(
        context.outputs[
            "block_relations"
        ],
        "block_relations",
    )

    bootstrap_replicates = require_dataframe(
        context.outputs[
            "bootstrap_replicates"
        ],
        "bootstrap_replicates",
    )

    relation_classification = (
        require_dataframe(
            context.outputs[
                "relation_classification"
            ],
            "relation_classification",
        )
    )

    equivalence_flags = require_dataframe(
        context.outputs[
            "equivalence_flags"
        ],
        "equivalence_flags",
    )

    write_csv(
        OUTPUT_PATHS[
            "candidate_relations"
        ],
        candidate_relations,
    )

    write_csv(
        OUTPUT_PATHS[
            "block_relations"
        ],
        block_relations,
    )

    write_csv(
        OUTPUT_PATHS[
            "bootstrap_relations"
        ],
        bootstrap_replicates,
    )

    write_csv(
        OUTPUT_PATHS[
            "relation_classification"
        ],
        relation_classification,
    )

    write_csv(
        OUTPUT_PATHS[
            "equivalence_flags"
        ],
        equivalence_flags,
    )

    write_json(
        OUTPUT_PATHS[
            "summary"
        ],
        summary,
    )

    OUTPUT_PATHS[
        "report"
    ].write_text(
        report_text,
        encoding="utf-8",
    )

    write_json(
        OUTPUT_PATHS[
            "manifest"
        ],
        manifest,
    )

    output_hashes = {
        name: sha256_file(path)
        for name, path
        in OUTPUT_PATHS.items()
    }

    return output_hashes


def build_experiment_result(
    summary: Mapping[str, Any],
    output_hashes: Mapping[str, str],
    manifest: Mapping[str, Any],
) -> ExperimentResult:
    """Build the immutable experiment result object."""
    scientific_claims = require_mapping(
        summary[
            "scientific_claims"
        ],
        "summary.scientific_claims",
    )

    status = str(
        summary[
            "scientific_outcome"
        ]
    )

    return ExperimentResult(
        experiment_id="CGIE3_ID_02",

        status=status,

        summary=dict(
            summary
        ),

        outputs={
            name: {
                "path":
                    str(
                        OUTPUT_PATHS[
                            name
                        ].relative_to(
                            REPOSITORY_ROOT
                        )
                    ),

                "sha256":
                    digest,
            }
            for name, digest
            in output_hashes.items()
        },

        scientific_claims={
            str(key): bool(value)
            for key, value
            in scientific_claims.items()
        },

        statistics={
            "relation_count":
                int(
                    summary[
                        "relation_count"
                    ]
                ),

            "status_counts":
                summary[
                    "status_counts"
                ],
        },

        warnings=(
            "Eligibility does not establish "
            "causality or indispensability.",

            "CGIE3-ID-02 does not establish "
            "earthquake prediction.",
        ),

        provenance={
            "manifest":
                manifest,
        },

        metadata={
            "generated_at_utc":
                summary[
                    "generated_at_utc"
                ],
        },
    )


def generate_reports(
    context: ExperimentContext,
) -> ExperimentResult:
    """Generate all official CGIE3-ID-02 scientific outputs."""
    validate_context(
        context
    )

    validate_output_row_counts(
        context
    )

    OUTPUT_DIRECTORY.mkdir(
        parents=True,
        exist_ok=True,
    )

    summary = build_summary(
        context
    )

    report_text = build_report(
        summary,
        context,
    )

    manifest = build_manifest(
        context,
        summary,
    )

    output_hashes = (
        write_scientific_outputs(
            context,
            summary,
            report_text,
            manifest,
        )
    )

    manifest_with_hashes = dict(
        manifest
    )

    manifest_with_hashes[
        "output_sha256"
    ] = output_hashes

    write_json(
        OUTPUT_PATHS[
            "manifest"
        ],
        manifest_with_hashes,
    )

    final_hashes = dict(
        output_hashes
    )

    final_hashes[
        "manifest"
    ] = sha256_file(
        OUTPUT_PATHS[
            "manifest"
        ]
    )

    context.register_output(
        "official_summary",
        summary,
    )

    context.register_output(
        "official_manifest",
        manifest_with_hashes,
    )

    context.register_output(
        "official_output_hashes",
        final_hashes,
    )

    context.register_runtime(
        "reporting_status",
        "COMPLETED",
    )

    return build_experiment_result(
        summary=summary,
        output_hashes=final_hashes,
        manifest=manifest_with_hashes,
    )
  
  
