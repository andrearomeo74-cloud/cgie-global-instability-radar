def markdown_table_rows(
    values: Mapping[str, Any],
) -> str:
    """Convert a mapping into Markdown table rows."""
    return "\n".join(
        f"| `{key}` | {value} |"
        for key, value
        in values.items()
    )


def build_report(
    summary: Mapping[str, Any],
    context: ExperimentContext,
) -> str:
    """Build the human-readable scientific report."""
    status_counts = require_mapping(
        summary["status_counts"],
        "summary.status_counts",
    )

    classification_by_window = (
        require_mapping(
            summary[
                "classification_by_window"
            ],
            "summary.classification_by_window",
        )
    )

    status_rows = markdown_table_rows(
        status_counts
    )

    window_sections: list[str] = []

    for window_id in sorted(
        classification_by_window
    ):
        counts = require_mapping(
            classification_by_window[
                window_id
            ],
            (
                "summary.classification_by_window."
                f"{window_id}"
            ),
        )

        rows = markdown_table_rows(
            counts
        )

        window_sections.append(
            f"""### Window `{window_id}`

| Status | Count |
|---|---:|
{rows}
"""
        )

    windows_text = "\n".join(
        window_sections
    )

    eligible_relations = (
        context.outputs[
            "relation_classification"
        ]
        .loc[
            lambda frame:
                frame[
                    "classification_status"
                ]
                == "eligible"
        ]
        .copy()
    )

    if eligible_relations.empty:
        eligible_text = (
            "No relation satisfied every frozen "
            "eligibility condition."
        )
    else:
        eligible_lines = []

        for row in eligible_relations.itertuples(
            index=False
        ):
            eligible_lines.append(
                "- "
                f"`{row.window_id}` — "
                f"`{row.source_id}` ↔ "
                f"`{row.target_id}`; "
                f"Spearman = "
                f"`{float(row.strength):.4f}`; "
                f"persistence = "
                f"`{float(row.persistence):.4f}`."
            )

        eligible_text = "\n".join(
            eligible_lines
        )

    return f"""# CGIE3-ID-02 — Eligible Relation Discovery Report

## Status

`{summary["technical_status"]}`

## Scientific outcome

`{summary["scientific_outcome"]}`

## Purpose

CGIE3-ID-02 evaluates whether relations among the frozen
Campi Flegrei seismic feature set satisfy a predetermined
baseline eligibility protocol.

The experiment does not test deterministic earthquake prediction.

## Dataset boundary

- Selection interval: frozen 2025 baseline only
- Evaluation data used for selection: `false`
- Target-event labels used for selection: `false`
- Candidate relations evaluated: `{summary["relation_count"]}`

## Overall classification

| Status | Count |
|---|---:|
{status_rows}

## Classification by temporal window

{windows_text}

## Eligible relations

{eligible_text}

## Interpretation

An `eligible` relation is one that satisfies the frozen requirements
for baseline strength, estimability, sign preservation, persistence,
bootstrap uncertainty, leave-one-block-out robustness and
missingness robustness.

Eligibility does **not** establish that a relation is:

- causal;
- indispensable;
- a primary identity relation;
- physically sufficient;
- predictive of a specific earthquake.

## Scientific claim boundary

{summary["claim_boundary"]}

## Explicit negative claims

- Primary relations established: `false`
- Indispensable relations established: `false`
- Causality established: `false`
- Predictive capability established: `false`
- Earthquake prediction established: `false`

## Reproducibility

The official output package includes:

- candidate relations;
- monthly block estimates;
- bootstrap replications;
- frozen relation classifications;
- equivalence and redundancy flags;
- summary;
- report;
- manifest.

Rejected and non-estimable relations remain preserved.

## Generated

`{summary["generated_at_utc"]}`
"""


