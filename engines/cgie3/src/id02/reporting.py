def fail(message: str) -> None:
    """Raise a reporting-stage error."""
    raise ReportingStageError(
        str(message).strip()
    )


def utc_now_iso() -> str:
    """Return current UTC time in canonical ISO-8601 format."""
    return (
        datetime.now(timezone.utc)
        .isoformat()
        .replace("+00:00", "Z")
    )


def require_mapping(
    value: Any,
    field_name: str,
) -> Mapping[str, Any]:
    """Require a mapping-like value."""
    if not isinstance(value, Mapping):
        fail(
            f"{field_name} must be a mapping."
        )

    return value


def require_dataframe(
    value: Any,
    field_name: str,
) -> pd.DataFrame:
    """Require a non-empty pandas DataFrame."""
    if not isinstance(
        value,
        pd.DataFrame,
    ):
        fail(
            f"{field_name} must be a pandas DataFrame."
        )

    if value.empty:
        fail(
            f"{field_name} must not be empty."
        )

    return value


def validate_context(
    context: ExperimentContext,
) -> None:
    """Validate all reporting-stage prerequisites."""
    if not isinstance(
        context,
        ExperimentContext,
    ):
        fail(
            "context must be an ExperimentContext."
        )

    if context.experiment_id != "CGIE3_ID_02":
        fail(
            "Unexpected experiment ID: "
            f"{context.experiment_id}"
        )

    required_outputs = {
        "candidate_relations",
        "block_relations",
        "bootstrap_replicates",
        "relation_classification",
        "equivalence_flags",
        "relation_discovery_summary",
        "persistence_summary",
        "bootstrap_stage_summary",
        "missingness_stage_summary",
        "classification_summary",
        "equivalence_summary",
        "preprocessing_quality_audit",
    }

    missing_outputs = sorted(
        required_outputs
        - set(context.outputs)
    )

    if missing_outputs:
        fail(
            "Reporting prerequisites are missing: "
            + ", ".join(missing_outputs)
        )

    required_runtime_stages = {
        "preprocessing_status",
        "relation_discovery_status",
        "persistence_status",
        "bootstrap_status",
        "missingness_status",
        "classification_status",
        "equivalence_status",
    }

    missing_runtime = sorted(
        required_runtime_stages
        - set(context.runtime)
    )

    if missing_runtime:
        fail(
            "Runtime stage records are missing: "
            + ", ".join(missing_runtime)
        )

    incomplete_stages = sorted(
        stage_name
        for stage_name
        in required_runtime_stages
        if context.runtime.get(stage_name)
        != "COMPLETED"
    )

    if incomplete_stages:
        fail(
            "Some experiment stages are not completed: "
            + ", ".join(incomplete_stages)
        )


def sha256_file(
    path: Path,
) -> str:
    """Calculate SHA-256 for one file."""
    if not path.exists():
        fail(
            f"File not found for hashing: {path}"
        )

    digest = hashlib.sha256()

    with path.open("rb") as handle:
        for block in iter(
            lambda: handle.read(
                1024 * 1024
            ),
            b"",
        ):
            digest.update(block)

    return digest.hexdigest()


def json_compatible(
    value: Any,
) -> Any:
    """
    Convert framework objects into strict JSON-compatible structures.

    Non-finite floating-point values become null.
    """
    if value is None:
        return None

    if isinstance(
        value,
        (
            str,
            bool,
            int,
        ),
    ):
        return value

    if isinstance(
        value,
        (
            np.integer,
        ),
    ):
        return int(value)

    if isinstance(
        value,
        (
            float,
            np.floating,
        ),
    ):
        normalized = float(value)

        if not np.isfinite(
            normalized
        ):
            return None

        return normalized

    if isinstance(
        value,
        pd.Timestamp,
    ):
        return value.isoformat()

    if isinstance(
        value,
        Path,
    ):
        return str(value)

    if isinstance(
        value,
        Mapping,
    ):
        return {
            str(key): json_compatible(item)
            for key, item
            in value.items()
        }

    if isinstance(
        value,
        (
            list,
            tuple,
            set,
        ),
    ):
        return [
            json_compatible(item)
            for item in value
        ]

    if hasattr(
        value,
        "__dataclass_fields__",
    ):
        return {
            field_name: json_compatible(
                getattr(
                    value,
                    field_name,
                )
            )
            for field_name
            in value.__dataclass_fields__
        }

    return str(value)


def write_json(
    path: Path,
    payload: Mapping[str, Any],
) -> None:
    """Write strict deterministic JSON."""
    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    compatible_payload = (
        json_compatible(
            payload
        )
    )

    path.write_text(
        json.dumps(
            compatible_payload,
            indent=2,
            ensure_ascii=False,
            sort_keys=True,
            allow_nan=False,
        )
        + "\n",
        encoding="utf-8",
    )


def write_csv(
    path: Path,
    frame: pd.DataFrame,
) -> None:
    """Write deterministic UTF-8 CSV."""
    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    output = frame.copy()

    for column in output.columns:
        if output[column].map(
            lambda value: isinstance(
                value,
                (
                    dict,
                    list,
                    tuple,
                    set,
                ),
            )
        ).any():
            output[column] = output[
                column
            ].map(
                lambda value: json.dumps(
                    json_compatible(value),
                    ensure_ascii=False,
                    sort_keys=True,
                )
                if isinstance(
                    value,
                    (
                        dict,
                        list,
                        tuple,
                        set,
                    ),
                )
                else value
            )

    output.to_csv(
        path,
        index=False,
        encoding="utf-8",
        lineterminator="\n",
        float_format="%.10g",
    )


def validate_output_row_counts(
    context: ExperimentContext,
) -> None:
    """Validate row counts before writing official outputs."""
    candidate_relations = (
        require_dataframe(
            context.outputs[
                "candidate_relations"
            ],
            "candidate_relations",
        )
    )

    classification = require_dataframe(
        context.outputs[
            "relation_classification"
        ],
        "relation_classification",
    )

    equivalence_flags = require_dataframe(
        context.outputs[
            "equivalence_flags"
        ],
        "equivalence_flags",
    )

    if len(
        candidate_relations
    ) != 136:
        fail(
            "candidate_relations must contain 136 rows."
        )

    if len(
        classification
    ) != 136:
        fail(
            "relation_classification must contain 136 rows."
        )

    if len(
        equivalence_flags
    ) != 136:
        fail(
            "equivalence_flags must contain 136 rows."
        )

    bootstrap_replicates = (
        require_dataframe(
            context.outputs[
                "bootstrap_replicates"
            ],
            "bootstrap_replicates",
        )
    )

    if len(
        bootstrap_replicates
    ) != 68000:
        fail(
            "bootstrap_replicates must contain "
            f"68000 rows; observed "
            f"{len(bootstrap_replicates)}."
        )


